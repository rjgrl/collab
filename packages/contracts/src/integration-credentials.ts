export function fieldRequired(field: CredentialField, values: Record<string, string | undefined>) {
  return field.requiredWhen
    ? values[field.requiredWhen.field] === field.requiredWhen.equals
    : field.required;
}

const serviceAccountSchema = z.object({
  client_email: z.string().email(),
  private_key: z.string().includes("PRIVATE KEY"),
});

/** Format check for one value; returns an error message or null. Never echoes the value. */
export function credentialFormatError(field: CredentialField, value: string): string | null {
  const trimmed = value.trim();
  if (trimmed.length > (field.kind === "json" ? 20000 : 2048)) return `${field.label} is too long.`;
  switch (field.kind) {
    case "url":
      try {
        return new URL(trimmed).protocol === "https:" ? null : `${field.label} must use https://.`;
      } catch {
        return `${field.label} must be a valid URL.`;
      }
    case "email":
      return z.string().email().safeParse(trimmed).success
        ? null
        : `${field.label} must be an email address.`;
    case "json":
      try {
        return serviceAccountSchema.safeParse(JSON.parse(trimmed)).success
          ? null
          : `${field.label} must contain client_email and private_key.`;
      } catch {
        return `${field.label} must be valid JSON.`;
      }
    case "choice":
      return field.options?.some((option) => option.value === trimmed)
        ? null
        : `Choose a valid ${field.label.toLowerCase()}.`;
    default:
      return /^[\x21-\x7e]+$/.test(trimmed) ? null : `${field.label} contains invalid characters.`;
  }
}

/** Returns the first missing-or-invalid message for an integration's values, else null. */
export function credentialsError(
  key: IntegrationKey,
  values: Record<string, string | undefined>,
): string | null {
  for (const field of INTEGRATION_CREDENTIAL_FIELDS[key]) {
    const value = values[field.name]?.trim() ?? "";
    if (!value) {
      if (fieldRequired(field, values)) return `${field.label} is required.`;
      continue;
    }
    const error = credentialFormatError(field, value);
    if (error) return error;
  }
  return null;
}

