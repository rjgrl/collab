export type IntegrationKey = z.infer<typeof integrationKeySchema>;

/**
 * Credential fields each integration needs before it can be enabled. Secret fields are
 * write-only: the API never returns them, only whether they are set and their last 4
 * characters. Non-secret fields (public site keys, IDs, URLs) are returned to administrators.
 * `env` names the development-only environment variable the seed CLI may copy into the DB.
 */
export type CredentialField = {
  name: string;
  label: string;
  secret: boolean;
  kind: "text" | "url" | "email" | "json" | "choice";
  /** Required unless `requiredWhen` says otherwise. */
  required: boolean;
  requiredWhen?: { field: string; equals: string };
  options?: readonly { value: string; label: string }[];
  hint?: string;
  env?: string;
};

